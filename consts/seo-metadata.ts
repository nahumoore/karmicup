/**
 * Builds a complete Metadata object for a page.
 *
 * Next.js merges metadata shallowly per top-level key, so overriding `openGraph`
 * or `twitter` in a page drops the root values (siteName, url, card type, image…).
 * This helper always returns the full objects plus a self-referencing canonical.
 */
export function buildPageMetadata(
  key: PageSeoKey,
  options: { path?: string; absoluteTitle?: boolean; noIndex?: boolean } = {},
): Metadata {
  const { title, description } = PAGE_SEO[key]
  const { path, absoluteTitle = false, noIndex = false } = options
  const fullTitle = absoluteTitle ? title : `${title} | ${SITE_NAME}`

  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    ...(path ? { alternates: { canonical: path } } : {}),
    openGraph: {
      siteName: SITE_NAME,
      locale: 'en_US',
      type: 'website',
      title: fullTitle,
      description,
      images: [DEFAULT_OG_IMAGE],
      ...(path ? { url: path } : {}),
    },
    twitter: {
      card: 'summary_large_image',
      title: fullTitle,
      description,
      images: [DEFAULT_OG_IMAGE],
    },
    ...(noIndex ? { robots: { index: false, follow: false } } : {}),
  }
}

